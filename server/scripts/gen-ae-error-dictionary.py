#!/usr/bin/env python3
"""Regenerate server/src/abi-engine/refdata/aeErrorDictionary.ts from CBP's
ACE CATAIR Entry Summary Error Dictionary (XLSX, cbp.gov).

Usage: python3 server/scripts/gen-ae-error-dictionary.py <dictionary.xlsx> <version-label>
Source page: https://www.cbp.gov/document/guidance/ace-catair-error-dictionary-v31
When a code appears more than once, the most recently dated row wins.
"""
import json, sys, datetime, openpyxl

src, version = sys.argv[1], sys.argv[2]
ws = openpyxl.load_workbook(src, read_only=True)['ACE Error Dictionary']
best = {}
for i, row in enumerate(ws.iter_rows(values_only=True)):
    if i == 0 or row[0] is None:
        continue
    code = str(row[0]).strip().upper().zfill(3)
    narrative = ' '.join(str(row[1] or '').split())
    explanation = ' '.join(str(row[2] or '').split())
    d = row[3]
    date = d.date().isoformat() if isinstance(d, datetime.datetime) else str(d or '').strip()
    if code not in best or date > best[code]['updated']:
        best[code] = {'narrative': narrative, 'explanation': explanation, 'updated': date}

out = sys.stdout
out.write('/**\n * CBP ACE CATAIR Entry Summary Error Dictionary, ' + version + '.\n')
out.write(' * GENERATED by server/scripts/gen-ae-error-dictionary.py from CBP\'s XLSX\n')
out.write(' * (docs/abi-engine/specs/reference-data/). Do not edit by hand.\n */\n')
out.write('export const AE_ERROR_DICTIONARY_VERSION = ' + json.dumps(version) + ';\n\n')
out.write('export interface AeErrorEntry {\n  narrative: string;\n  explanation: string;\n  updated: string;\n}\n\n')
out.write('export const AE_ERROR_DICTIONARY: Record<string, AeErrorEntry> = {\n')
for code in sorted(best):
    e = best[code]
    out.write('  ' + json.dumps(code) + ': ' + json.dumps(e, ensure_ascii=False) + ',\n')
out.write('};\n')
