#!/usr/bin/env python3
"""Regenerate server/src/services/htsClassifier/htsNotes.ts: the HTSUS section
and chapter notes (legal notes, additional U.S. notes, statistical notes) the
HTS classifier gives the AI. Public domain, published by USITC per chapter as
PDF; the text before each chapter's first tariff table is the notes.

Usage: python3 server/scripts/gen-hts-notes.py <pdf-dir> <revision-label> > server/src/services/htsClassifier/htsNotes.ts
Needs pdftotext (poppler). PDFs are downloaded into <pdf-dir> when missing:
https://hts.usitc.gov/reststop/file?release=currentRelease&filename=Chapter%20NN
Re-run when USITC publishes a new revision.
"""
import json, os, re, subprocess, sys, time, urllib.request

pdf_dir, revision = sys.argv[1], sys.argv[2]
URL = 'https://hts.usitc.gov/reststop/file?release=currentRelease&filename=Chapter%20{}'
ROMAN = r'(?:[IVX]+)'

# Page furniture repeated on every page.
NOISE = [
    re.compile(r'^\s*Harmonized Tariff Schedule of the United States.*$'),
    re.compile(r'^\s*Annotated for Statistical Reporting Purposes\s*$'),
    re.compile(r'^\s*' + ROMAN + r'(-\d+)?\s*$'),
    re.compile(r'^\s*\d{1,2}-\d+\s*$'),
    re.compile(r'^\s*' + ROMAN + r'\s+\d{1,2}-\d+\s*$'),
]


def text_of(ch):
    pdf = os.path.join(pdf_dir, f'ch{ch:02d}.pdf')
    for attempt in range(6):
        if os.path.exists(pdf):
            break
        try:  # USITC answers 503 when fetched quickly; back off and retry
            urllib.request.urlretrieve(URL.format(ch), pdf + '.part')
            os.rename(pdf + '.part', pdf)
        except Exception:
            if attempt == 5:
                raise
            time.sleep(5 * (attempt + 1))
    return subprocess.run(['pdftotext', '-layout', pdf, '-'], capture_output=True, text=True, check=True).stdout


def clean(block):
    """Drop page furniture and reflow wrapped lines into paragraphs."""
    lines = [l for l in block.splitlines() if not any(p.match(l) for p in NOISE)]
    paras, cur = [], []
    for l in lines:
        if not l.strip():
            if cur:
                paras.append(' '.join(cur))
                cur = []
            continue
        cur.append(l.strip())
    if cur:
        paras.append(' '.join(cur))
    return '\n'.join(re.sub(r'\s{2,}', ' ', p) for p in paras).strip()


sections, chapters = {}, {}
current_section = None
for ch in range(1, 98):
    if ch == 77:  # reserved for future use
        continue
    raw = text_of(ch)
    table = re.search(r'^\s*Heading/\s+Stat\.', raw, re.M)
    head = raw[: table.start()] if table else raw
    sec = re.search(r'^\s*SECTION\s+(' + ROMAN + r')\s*$', head, re.M)
    chap = re.search(r'^\s*CHAPTER\s+' + str(ch) + r'\s*$', head, re.M)
    if sec and chap and sec.start() < chap.start():
        current_section = sec.group(1)
        sections[current_section] = clean(head[sec.end(): chap.start()])
    body = head[chap.end():] if chap else head
    chapters[f'{ch:02d}'] = {'section': current_section, 'notes': clean(body)}

out = sys.stdout
out.write('/**\n * HTSUS section and chapter notes, ' + revision + ' (USITC, public domain).\n')
out.write(' * GENERATED by server/scripts/gen-hts-notes.py from the USITC chapter PDFs.\n')
out.write(' * Do not edit by hand.\n */\n')
out.write('export const HTS_NOTES_REVISION = ' + json.dumps(revision) + ';\n\n')
out.write('export const SECTION_NOTES: Record<string, string> = ' + json.dumps(sections, indent=0, ensure_ascii=False) + ';\n\n')
out.write('export const CHAPTER_NOTES: Record<string, { section: string | null; notes: string }> = ' + json.dumps(chapters, indent=0, ensure_ascii=False) + ';\n')
